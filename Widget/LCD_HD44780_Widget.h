    static void RenderChar(ImDrawList* draw, ImVec2 pos, unsigned char c, float pSize, ImU32 colOn, ImU32 colOff) {
        const LCDCharData* font = GetFont();
        const LCDCharData& data = font[c];
        for (int y = 0; y < 8; ++y) {
            for (int x = 0; x < 5; ++x) {
                bool active = (data.rows[y] >> (4 - x)) & 0x01;
                ImVec2 p1(pos.x + x * pSize, pos.y + y * pSize);
                ImVec2 p2(p1.x + pSize - 0.5f, p1.y + pSize - 0.5f);
                draw->AddRectFilled(p1, p2, active ? colOn : colOff);
            }
        }
    }

    static void DrawLCD(const char* line1, const char* line2, float pSize) {
        ImGuiWindow* window = ImGui::GetCurrentWindow();
        if (window->SkipItems) return;

        ImDrawList* draw = window->DrawList;
        ImVec2 pos = window->DC.CursorPos;

        const float charGap = 2.0f;
        const float charW = 5 * pSize;
        const float charH = 8 * pSize;
        const ImVec2 lcdPadding(10, 10);

        float displayW = 16 * (charW + charGap) + lcdPadding.x * 2;
        float displayH = 2 * (charH + 8) + lcdPadding.y * 2;
        float pcbW = displayW + 40;
        float pcbH = displayH + 40;

        // PCB
        draw->AddRectFilled(pos, ImVec2(pos.x + pcbW, pos.y + pcbH), IM_COL32(34, 80, 34, 255), 5.0f);
        for (int i = 0; i < 16; ++i)
            draw->AddCircleFilled(ImVec2(pos.x + 30 + i * 15, pos.y + 10), 3.0f, IM_COL32(200, 180, 50, 255));

        // Black frame
        ImVec2 framePos(pos.x + 20, pos.y + 25);
        draw->AddRectFilled(framePos, ImVec2(framePos.x + displayW, framePos.y + displayH), IM_COL32(15, 15, 15, 255), 3.0f);

        // Yellow area
        ImVec2 lcdPos(framePos.x + 5, framePos.y + 5);
        ImVec2 lcdMax(framePos.x + displayW - 5, framePos.y + displayH - 5);
        draw->AddRectFilled(lcdPos, lcdMax, IM_COL32(165, 195, 0, 255));

        // Characters
        auto draw_line = [&](const char* text, int row) {
            if (!text) return;
            for (int i = 0; i < 16; ++i) {
                unsigned char c = (i < (int)std::strlen(text)) ? (unsigned char)text[i] : ' ';
                ImVec2 cPos(lcdPos.x + 5 + i * (charW + charGap),
                    lcdPos.y + 5 + row * (charH + 8));
                RenderChar(draw, cPos, c, pSize, IM_COL32(40, 50, 0, 240), IM_COL32(145, 175, 0, 80));
            }
            };

        draw_line(line1, 0);
        draw_line(line2, 1);

        // Highlight
        draw->AddRectFilledMultiColor(lcdPos, ImVec2(lcdMax.x, lcdPos.y + 15),
            IM_COL32(255, 255, 255, 60), IM_COL32(255, 255, 255, 60),
            IM_COL32(255, 255, 255, 0), IM_COL32(255, 255, 255, 0));

        ImGui::Dummy(ImVec2(pcbW, pcbH));
    }
