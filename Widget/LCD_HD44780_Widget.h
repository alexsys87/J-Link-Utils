    void Draw(MainContext* ctx, uint32_t* dynamicAddr) override {
        char line1[17] = { 0 };
        char line2[17] = { 0 };

        if (useFixed) {
            // Fixed mode: only the fixed text is shown
            strncpy_s(line1, fixedLine1.c_str(), sizeof(line1) - 1);
            strncpy_s(line2, fixedLine2.c_str(), sizeof(line2) - 1);
        }
        else {
            // Always read memory at the given addresses (even if an address is 0)
            readLine(ctx, line1Addr, line1, sizeof(line1) - 1);
            readLine(ctx, line2Addr, line2, sizeof(line2) - 1);
        }

        ImGui::PushID(this);
        DrawLCD(line1, line2, pixelSize);
        ImGui::PopID();
    }

private:
    // Reads a line (up to 16 characters) starting at the base address
    void readLine(MainContext* ctx, uint32_t baseAddr, char* out, int maxLen) const {
        for (int i = 0; i < maxLen; i += 4) {
            uint32_t word = DataReadWriteU32(ctx, nullptr, nullptr, &baseAddr);
            for (int j = 0; j < 4; ++j) {
                int idx = i + j;
                if (idx >= maxLen) break;
                if (littleEndian) {
                    // little-endian: the low byte (j=0) is the first character
                    out[idx] = (char)((word >> (8 * j)) & 0xFF);
                }
                else {
                    // big-endian: the high byte (j=0) is the first character
                    out[idx] = (char)((word >> (8 * (3 - j))) & 0xFF);
                }
            }
            baseAddr += 4; // next 32-bit word
        }
        out[maxLen] = '\0';
    }

