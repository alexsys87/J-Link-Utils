    // Чтение строки (до 16 символов) из памяти по базовому адресу
    void readLine(MainContext* ctx, uint32_t baseAddr, char* out, int maxLen) const {
        for (int i = 0; i < maxLen; i += 4) {
            uint32_t word = DataReadWriteU32(ctx, nullptr, nullptr, &baseAddr);
            for (int j = 0; j < 4; ++j) {
                int idx = i + j;
                if (idx >= maxLen) break;
                if (littleEndian) {
                    // little-endian: младший байт (j=0) – первый символ
                    out[idx] = (char)((word >> (8 * j)) & 0xFF);
                }
                else {
                    // big-endian: старший байт (j=0) – первый символ
                    out[idx] = (char)((word >> (8 * (3 - j))) & 0xFF);
                }
            }
            baseAddr += 4; // переходим к следующему 32‑битному слову
        }
        out[maxLen] = '\0';
    }

