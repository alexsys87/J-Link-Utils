#!/usr/bin/env python3
"""Draws the application icon and writes every file that uses it.

  res/app.ico       Windows icon (16..256 px), linked into the executable by res/app.rc
  res/app_icon.png  256 px preview
  res/app_icon.h    64 px RGBA pixels for SDL_SetWindowIcon() and the About window

The icon is a microcontroller with a live signal on it, on a blue tile.
Requires Pillow. Run: python3 res/make_icon.py
"""
from pathlib import Path
from PIL import Image, ImageDraw
import math

HERE = Path(__file__).resolve().parent


def lerp(a, b, t):
    return tuple(int(round(a[i] + (b[i] - a[i]) * t)) for i in range(len(a)))


def draw(size, pins):
    """The icon drawn at 8x and scaled down; small sizes use fewer pins and thicker lines."""
    s = size * 8
    k = s / 1024.0
    img = Image.new('RGBA', (s, s), (0, 0, 0, 0))

    # Tile with a vertical gradient
    gradient = Image.new('RGBA', (s, s))
    gd = ImageDraw.Draw(gradient)
    top, bottom = (46, 132, 238, 255), (16, 58, 138, 255)
    for y in range(s):
        gd.line([(0, y), (s, y)], fill=lerp(top, bottom, y / (s - 1)))
    mask = Image.new('L', (s, s), 0)
    ImageDraw.Draw(mask).rounded_rectangle([24 * k, 24 * k, s - 24 * k, s - 24 * k], radius=190 * k, fill=255)
    img.paste(gradient, (0, 0), mask)
    d = ImageDraw.Draw(img)

    # Pins on all four sides
    body0, body1 = 262 * k, 762 * k
    pin_len = 112 * k
    pin_w = (64 if pins <= 3 else 50) * k
    pin_color = (220, 228, 236, 255)
    span = body1 - body0
    for i in range(pins):
        c = body0 + span * (i + 1) / (pins + 1)
        a, b = c - pin_w / 2, c + pin_w / 2
        r = pin_w * 0.3
        d.rounded_rectangle([a, body0 - pin_len, b, body0 + 10 * k], radius=r, fill=pin_color)   # top
        d.rounded_rectangle([a, body1 - 10 * k, b, body1 + pin_len], radius=r, fill=pin_color)   # bottom
        d.rounded_rectangle([body0 - pin_len, a, body0 + 10 * k, b], radius=r, fill=pin_color)   # left
        d.rounded_rectangle([body1 - 10 * k, a, body1 + pin_len, b], radius=r, fill=pin_color)   # right

    # Chip body with a lighter rim
    d.rounded_rectangle([body0, body0, body1, body1], radius=64 * k, fill=(64, 82, 104, 255))
    d.rounded_rectangle([body0 + 18 * k, body0 + 18 * k, body1 - 18 * k, body1 - 18 * k], radius=50 * k, fill=(28, 38, 52, 255))

    # Pin 1 mark
    if pins > 3:
        d.ellipse([body0 + 52 * k, body0 + 52 * k, body0 + 100 * k, body0 + 100 * k], fill=(96, 118, 142, 255))

    # Signal: one period of a sine between two flat parts
    x0, x1 = body0 + 70 * k, body1 - 70 * k
    yc, amp = 520 * k, 125 * k
    points = []
    steps = 120
    for i in range(steps + 1):
        t = i / steps
        x = x0 + (x1 - x0) * t
        if t < 0.15 or t > 0.85:
            y = yc
        else:
            y = yc - amp * math.sin((t - 0.15) / 0.7 * 2 * math.pi)
        points.append((x, y))
    width = int((70 if pins <= 3 else 48) * k)
    d.line(points, fill=(72, 232, 132, 255), width=width, joint='curve')
    for p in (points[0], points[-1]):
        d.ellipse([p[0] - width / 2, p[1] - width / 2, p[0] + width / 2, p[1] + width / 2], fill=(72, 232, 132, 255))

    return img.resize((size, size), Image.LANCZOS)


def main():
    sizes = [16, 20, 24, 32, 40, 48, 64, 128, 256]
    images = {n: draw(n, 3 if n <= 24 else 4 if n <= 48 else 5) for n in sizes}
    images[256].save(HERE / 'app_icon.png')
    images[256].save(HERE / 'app.ico', sizes=[(n, n) for n in sizes],
                     append_images=[images[n] for n in sizes if n != 256])

    px = images[64].tobytes()
    lines = ['// app_icon.h - generated by res/make_icon.py, do not edit.',
             '// 64 x 64 application icon, RGBA bytes in memory order (SDL_PIXELFORMAT_RGBA32).',
             '#pragma once', '',
             'static const int kAppIconSize = 64;',
             'static const unsigned char kAppIconPixels[64 * 64 * 4] = {']
    for i in range(0, len(px), 32):
        lines.append('    ' + ','.join(str(b) for b in px[i:i + 32]) + ',')
    lines.append('};')
    (HERE / 'app_icon.h').write_bytes(('\r\n'.join(lines) + '\r\n').encode('ascii'))


if __name__ == '__main__':
    main()
